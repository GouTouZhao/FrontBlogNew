/**
 * 复制文本到剪贴板（优先使用 Clipboard API，失败时回退到 execCommand）
 * @param {string} text
 * @returns {Promise<void>}
 */
export async function copyWithClipboardFallback(text) {
  if (navigator.clipboard && typeof navigator.clipboard.writeText === "function") {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch (_) {
      // 回退到传统复制方式
    }
  }
  copyText(text);
}

/**
 * 根据用户输入的主题/大概描述，即时拼接生成可直接发给 AI 的标准化提示词
 * @param {Object} options
 * @param {string} options.topic 用户输入的主题或对话大概描述
 * @param {"single"|"batch"} [options.mode="single"] 生成模式（单张图 / 批量多张图）
 * @param {string} [options.modelLabel="华为细圆"] 目标机型文案
 * @param {string} [options.otherName=""] 指定对方昵称（可选）
 * @returns {string}
 */
export function buildAiChatPrompt({
  topic = "",
  mode = "single",
  modelLabel = "华为细圆",
  otherName = "",
} = {}) {
  const cleanTopic = String(topic || "").trim();
  const cleanOther = String(otherName || "").trim();
  const isBatch = mode === "batch";

  const modeRequirement = isBatch
    ? `- 本次需要生成【多张连续或分场景的微信聊天图】，不同图片之间必须用单独一行 \`---\` 隔开（首图写完整顶部设置，后续图片若修改时间/电量/用户名可重写对应行，未改动可省略）。`
    : `- 本次生成【单张微信聊天图】，只输出一套完整的对话文本，不要出现 \`---\` 分隔符。`;

  const nicknameRule = cleanOther
    ? `- \`对方用户名\` 固定填写：\`${cleanOther}\`。`
    : `- \`对方用户名\` 请根据对话主题自动起一个自然贴合的微信昵称。`;

  const exampleBlock = isBatch ? STANDARD_TEXT_EXAMPLE_BATCH : STANDARD_TEXT_EXAMPLE_SINGLE;

  const userTopicBlock = cleanTopic
    ? cleanTopic
    : "（请在此填写你的对话主题/大概剧情，例如：朋友找我借钱周转，先寒暄几句，我转账500元给对方并附备注，对方收款后发语音致谢）";

  return `请你作为微信聊天脚本编剧与格式转换助手，根据我提供的“对话主题/大概描述”，生成一段**可直接导入微信聊天生成工具**的标准化纯文本。

【一、强制输出要求（务必严格遵守）】
1. **只输出可导入的纯文本内容**（可直接放在单个纯文本代码块内，不要输出任何前言、解释、序号、Markdown 加粗或多余空行说明）。
2. 每条内容必须严格占一行，使用 \`：\` 分隔字段；消息内部如果需要换行，**必须使用字面量 \`\\n\`**，不能直接回车折行。
3. 发送者角色**只能写 \`我\` 或 \`对方\`**，绝对不要在消息行里写具体昵称（昵称仅写在顶部的 \`对方用户名：...\`）。
${modeRequirement}
${nicknameRule}
4. 默认头部 \`机型\` 请写：\`机型：${modelLabel || "华为细圆"}\`。
5. 如果出现 \`时间：\` 行，小时为 0~9 点时不带前导 0（如写 \`时间：9:56\` 或 \`时间：昨天 下午9:56\`，不要写 \`09:56\`）。
6. 只使用下面规定的标准行格式，不要自造新标签。

【二、标准行格式说明】
- 顶部系统配置（放最前）：
  - \`机型：华为细圆\`（或 \`默认机型\`）
  - \`手机时间：HH:mm\`（如 \`手机时间：9:56\`）
  - \`手机电量：数字%\`（如 \`手机电量：82%\`）
  - \`对方用户名：昵称\`
- 消息类型（按剧情自然穿插即可，不必全用）：
  - 普通文本：\`文本：我：消息内容\` / \`文本：对方：消息内容\`（拒收带感叹号写 \`文本(拒收)：我：消息内容\`）
  - 时间戳：\`时间：昨天 下午9:40\` 或 \`时间：9:56\`（无发送者）
  - 语音消息：\`语音：对方：5秒\` 或 \`语音：我：12秒：转文字内容\`（秒数 1~60）
  - 语音/视频通话：\`通话：我：通话时长 02:15\`、\`通话：对方：已取消\` / \`已拒绝\` / \`忙线未接听\` / \`未接听\`（视频将 \`通话\` 改为 \`视频通话\`）
  - 转账与收款：\`转账：我：88.00元：备注文字\`、\`转账收款：对方：88.00元\`
  - 红包与领取：\`红包：对方：恭喜发财，大吉大利\`、\`红包领取：我：领取了红包\`
  - 撤回消息：\`撤回：我\` 或 \`撤回：对方\`（后面不再加内容）
  - 拍一拍/系统/图片/名片：\`拍一拍：你 拍了拍 "昵称" 的脑门\`、\`系统：提示文本\`、\`图片：我：[图片]\`、\`名片：对方：个人名片\`${
    isBatch ? "\n  - 分图分隔符：不同图片之间单独一行写 `---`" : ""
  }

【三、标准化输出示例（严格对齐此风格）】
\`\`\`text
${exampleBlock}
\`\`\`

【四、我的对话主题 / 大概描述】
${userTopicBlock}

请严格按照上述格式直接输出最终纯文本：`;
}

